use std::{fs, path::Path};

fn ensure_fallback_icon() {
    let icon_dir = Path::new("icons");
    let icon_path = icon_dir.join("icon.png");
    if icon_path.exists() {
        return;
    }

    fs::create_dir_all(icon_dir).expect("create Tauri icon directory");

    // Tiny valid PNG used only as a build-safe fallback. Release packaging
    // replaces this with the branded JARVIS icon pack.
    const PNG: &[u8] = &[
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
        0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
        0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4,
        0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41,
        0x54, 0x78, 0x9c, 0x63, 0x60, 0xd8, 0xf2, 0xff,
        0x3f, 0x00, 0x05, 0x1e, 0x02, 0xb3, 0xe7, 0xb7,
        0x2b, 0x65, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
        0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ];
    fs::write(icon_path, PNG).expect("write fallback Tauri icon");
}

fn main() {
    ensure_fallback_icon();
    tauri_build::build()
}
